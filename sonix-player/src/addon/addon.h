#ifndef ADDON_H
#define ADDON_H

#include <stdbool.h>
#include <stdint.h>

#include "src/gui/shell/gui.h"

#include "lvgl/lvgl.h"

// Addons: applications that are not in the binary.
//
// The Streaming and More pages are tiled sections, and every tile there is a
// compiled-in module. That is right for the things that ship with the player
// and wrong for everything else: a service whose API changes twice a year, an
// experiment, somebody else's app. Those live on the card instead, in
//
//     <card>/Addons/<id>/addon.json     what it is, and where its tile goes
//     <card>/Addons/<id>/addon.so       the code, MIPS32 LE, built by us
//     <card>/Addons/<id>/icon.png       optional, the tile's picture
//
// and the shell reads the folder at start-up, puts a tile on the section the
// manifest asks for, and does nothing more until that tile is tapped -- the
// library is opened then, by dlopen, and stays open until the player exits.
//
// The interface between the two halves is the pair of structures below. The
// .so exports exactly one function,
//
//     const sonix_addon_t *sonix_addon_entry(uint32_t api);
//
// and returns NULL when it does not speak `api`. Everything it does after that
// it does the way the rest of the interface does: it builds LVGL objects with
// the player's own widgets, calls http_get()/json_parse(), plays a stream with
// radio_play(). The addon is a module of this program that happened to arrive
// on a card, not a script in a sandbox -- see docs/ADDONS.md for what that
// means for trust, for threads, and for the ABI.
//
// The player exports its symbols for this, and only the ones an addon asks for:
// a library dlopen()ed by an executable resolves its undefined symbols against
// that executable's dynamic symbol table, and without the flag that table holds
// nothing but libgcc and libstdc++. The flag is -Wl,--dynamic-list with
// src/addon/exports.list, not -rdynamic: an exported symbol is a root for
// --gc-sections, so -rdynamic would keep every function nothing calls and cost
// 7.3 MB to 8.9 MB, which the rootfs volume does not have. The list is
// regenerated by tools/addon_exports.sh after `make target`; a name missing from
// it is a dlopen() on the device that says "undefined symbol".

// Bumped when either structure changes shape or meaning. An addon built
// against another number is refused with a sentence rather than a SIGSEGV:
// both halves are C structs, and a field added in the middle is a crash in a
// place that has nothing to do with the change.
#define SONIX_ADDON_API 1

#define ADDON_ID_MAX 32
#define ADDON_TITLE_MAX 64
#define ADDON_PATH_MAX 512

// What the shell tells the addon about itself. Valid for the lifetime of the
// process; the addon keeps the pointer.
typedef struct {
	const char *id;			 // the directory name, e.g. "myapp"
	const char *dir;		 // <card>/Addons/<id>, no trailing slash
	const char *sd_root;	 // the card's root, as the rest of the player knows it
	gui_config_t *cfg;      // screen size, padding, the bar height
} sonix_addon_host_t;

// What the addon tells the shell. The addon owns this structure -- it is
// usually a file-scope static in the .so -- and it has to stay alive.
typedef struct {
	uint32_t api; // SONIX_ADDON_API as the addon was built against

	// The tile's caption, after tr() and the manifest's own translations have
	// been tried. Points into the manifest, which the shell owns.
	const char *title;

	// Called once, on the UI thread, the first time the tile is tapped, before
	// anything is shown. Building screens here rather than at start-up is what
	// keeps an addon nobody opens free of both memory and time.
	//
	// Returns the screen the tile opens, or NULL when the addon cannot start.
	// Returning it rather than filling in a field is deliberate: the shell
	// never has to trust that a library kept its own descriptor in step with
	// what init() built.
	//
	// Navigation inside the addon is the addon's own business: switch_screen()
	// and the back-stack are public and work as they do everywhere else.
	//
	// How it stops is the *other* entry symbol (sonix_addon_stop_entry, below):
	// an addon is unloaded when the card leaves or when its files change on the
	// card, so a library that cannot say how to stop is refused at the door. An
	// addon with a file to flush still flushes it after each write -- stop() is
	// for threads, timers and registrations, not for correctness of the data.
	lv_obj_t *(*init)(const sonix_addon_host_t *host);
} sonix_addon_t;

typedef const sonix_addon_t *(*sonix_addon_entry_fn)(uint32_t api);

// ---------------------------------------------------------------------------
// The service half
//
// Most addons are apps: a tile, a screen, and nothing the rest of the player
// needs to know about. A *service* is the other kind -- it puts its tracks on
// the card in a cache of its own and hands them to the player's queue, so the
// player has to answer questions about files it did not create: is this ours,
// is a download running, may the device sleep, what does the star do, whose
// playlists does the picker offer. That is Qobuz, Tidal, Yandex Music, Zvuk.
//
// Two halves, because those questions come from two different times:
//
//   * **before the library is loaded.** The manifest says where the service
//     keeps its files -- "owns_paths" (path prefixes) and "cache_path" (the
//     directory to empty at exit and on a factory reset). USB export, the sleep
//     timer and the cleanup at exit are answered from that, with no .so opened
//     and no page visited, which matters because the player asks during boot
//     and from its own threads.
//   * **once the page exists.** Everything about the account -- the star, "add
//     to playlist", the mark over the artwork, "show album" -- is code, and it
//     arrives with the library. The addon exports it under a *second* name,
//     `sonix_addon_service_entry`, so an app addon built against this header
//     keeps working: the loader dlsym()s it and treats its absence as "an app".
//
// The threads: set_root, owns_path, cache_dir, downloading and network_wanted
// are asked from anywhere and must not touch LVGL; the account calls
// (fav_*, playlists_*) are made on the UI thread and their `done` arrives on
// the service's own worker, as everywhere else (gui_post is the way back).
// ---------------------------------------------------------------------------

#include "src/addon/addon_service.h"

// ---------------------------------------------------------------------------
// Unloading: the stop half
//
// An addon used to live as long as the process did, and addon.h said so: "there
// is no deinit". The card made that untenable. A dlopen()ed .so is a mapping of
// a file on the card, and a mapping keeps the filesystem alive after the card is
// pulled -- the mount is detached lazily, the dead superblock survives, and any
// read of it blocks in the card controller. Two copies of one addon then exist
// (the mapping and the reload), each with its own statics and its own workers,
// and the interface freezes.
//
// So a library that wants to be an addon now has to say how it stops. The
// contract, in one sentence: `stop()` runs on the GUI thread, and after it
// returns the library may be dlclose()d -- every thread it started has been
// joined or has exited, every lv_timer_t it created is deleted, every callback
// it registered with the player (service_register, theme_register_refresh,
// device_state_add_prepare_cb, its own back guards) is withdrawn, and every
// descriptor it holds is closed. init() must then work again, as on a fresh
// library.
//
// The hook is a second symbol rather than a field in sonix_addon_t, for the same
// reason the service table is: a field in the middle of the structure is a
// different structure, and a library built against the old one would crash the
// player on load instead of being refused.
// ---------------------------------------------------------------------------

#define SONIX_ADDON_STOP_ENTRY "sonix_addon_stop_entry"

typedef struct {
	uint32_t api;

	// See above. Called with the addon's screens already off the display and
	// nothing on the back-stack pointing at them; the shell deletes them after
	// this returns.
	//
	// TRUE MEANS THE LIBRARY IS SAFE TO UNLOAD -- every thread is out. FALSE is
	// the honest answer of an addon whose worker is still inside a socket that
	// the player cannot interrupt: the shell then keeps the mapping, says so in
	// the log and refuses to open that addon again for the rest of the run, which
	// is a leak instead of a jump into unmapped code.
	bool (*stop)(void);
} sonix_addon_stop_t;

typedef const sonix_addon_stop_t *(*sonix_addon_stop_entry_fn)(uint32_t api);

// Every screen the addon creates, registered as it is created (init() and any
// screen opened later), with the id the host gave it. The shell needs the list
// to unload: it moves the display off whichever of them is up, forgets them all
// in the back-stack and the player sheet, and deletes them after stop(). Without
// this it knows only the screen init() returned, and an addon left on its own
// sub-page keeps widget callbacks pointing into a library that is about to be
// unmapped. Screens the player built (main_menu_screen and its own pages) must
// never be registered.
void sonix_addon_own_screen(const char *id, lv_obj_t *screen);

// ---------------------------------------------------------------------------
// The shell's half. Everything below is the player's, and an addon has no use
// for it.
// ---------------------------------------------------------------------------

typedef enum {
	ADDON_SECTION_STREAMING = 0,
	ADDON_SECTION_MORE = 1,
} addon_section_t;

// How many addons are read; past this the rest are ignored and the log says
// so. Sixteen tiles is more than either section can show without scrolling.
#define ADDON_MAX 16

typedef struct {
	const char *id;
	const char *title;
	addon_section_t section;
	const lv_image_dsc_t *icon; // the addon's own picture, or the fallback
	int order;					// the place it asked for in its section, or 0

	// The service half, straight out of the manifest (see above): true when the
	// manifest says "service", and the paths that answer "is this file yours"
	// before the library is opened.
	bool is_service;
	int owns_count;
	const char *const *owns_paths; // prefixes, e.g. "<card>/.local/qobuz-cache/"
	const char *cache_path;		   // wiped at exit and on a factory reset, or NULL
} addon_info_t;

// Reads <card>/Addons once, on the UI thread, before the pages that show its
// tiles are built. Missing card, missing folder and unreadable manifests are
// not errors: the player simply has no addons, which is how it shipped.
void addon_scan(const gui_config_t *cfg);

int addon_count(void);

// NULL for an index out of range. The pointer stays valid: the list is filled
// once and never moved.
const addon_info_t *addon_get(int index);

// The screens this addon has on the display, in the order it registered them;
// NULL past the end. addon_unload() walks this list, so a page the addon opened
// by itself is taken off the display rather than left there with callbacks into
// a library that is being unmapped.
#define ADDON_SCREENS_MAX 8

// The stop half of the ABI (addon.h): implemented here so that an addon only has
// to export `sonix_addon_stop_entry`.
void sonix_addon_own_screen(const char *id, lv_obj_t *screen);

// dlopen + init + switch_screen, in that order, the first time; afterwards the
// screen is already there. Worth calling only from a tile callback. False when
// the addon could not be opened -- the reason has already been shown to the
// user.
//
// The library is reloaded when its files on the card changed since it was
// opened: an addon updated over USB, over the network or by pulling the card
// runs the new code the next time its tile is tapped, with no reboot. That is
// the hot-plug half of this interface; it needs the addon's stop hook (above).
bool addon_open(int index);

// Stops and unloads one addon: off the display, off the back-stack, stop(), the
// screens deleted, dlclose(). Called on the GUI thread; safe on an addon that
// was never opened (it just forgets the slot). False when the library could not
// be unloaded, in which case it stays mapped and the log says why.
bool addon_unload(int index);

// The same for every open addon, for the card leaving. Waits (bounded) for the
// GUI thread, so that the caller can unmount the card only once nothing is
// mapped from it: this is what turns "detached it lazily" into a plain unmount.
// True when every library was stopped and closed (or there was nothing open).
bool addon_card_gone(void);

// What the shell does when the folder changes: called on the UI thread right
// after a rescan, to put the new set of tiles on the pages.
void addon_set_refresh_hook(void (*hook)(void));

// Fills `entries` with one grid entry per addon of `section`, up to `max`, and
// returns how many were written. `entries` is the caller's array, appended to
// its own tiles; gridpage_build() reads the entries and keeps nothing.
int addon_fill_entries(addon_section_t section, void *entries, int max);

#endif /* ADDON_H */
